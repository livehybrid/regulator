@dataclass
class SlotPlan:
    slot: int
    engine: str
    share: Dict[str, Any]


@dataclass
class GroupPlan:
    engine: str
    image: str
    workers: int
    scenario_files: Dict[str, str]
    slots: List[SlotPlan] = field(default_factory=list)


def _scenario_files(directory: Path, scenario: Scenario) -> Dict[str, str]:
    files = {"scenario.yaml": (directory / "scenario.yaml").read_text(encoding="utf-8")}
    if scenario.searches is not None:
        conf = directory / scenario.searches.file
        if conf.is_file():
            files[scenario.searches.file] = conf.read_text(encoding="utf-8")
    return files


def _sub_scenario_yaml(text: str, engine: str) -> str:
    """The scenario with only the personas of one engine, for a mixed run.

    A mixed scenario becomes two worker groups on two images. Each group runs
    the same scenario file minus the other engine's personas, with the
    engine declared so lint agrees, and the same seed so the draws line up.
    """
    document = yaml.safe_load(text) or {}
    personas = []
    for persona in document.get("personas") or []:
        steps = persona.get("steps") or []
        engines = {str(step.get("engine", "api")).lower() for step in steps}
        if persona.get("steps_from"):
            engines.add("api")
        if engine in engines or not engines:
            personas.append(persona)
    document["personas"] = personas
    document["engine"] = engine
    return yaml.safe_dump(document, sort_keys=False)


def _split_evenly(total: int, workers: int) -> List[int]:
    base, remainder = divmod(int(total), workers)
    return [base + (1 if index < remainder else 0) for index in range(workers)]


def plan(run: Run, scenario: Scenario, directory: Path, settings: FleetSettings) -> List[GroupPlan]:
    """Split the run into worker groups and slots.

    One group per engine the scenario uses. Within a group the closed model's
    virtual users are dealt out as evenly as possible; the open model's
    arrival rate is divided; the schedule model's cron steps are dealt out by
    the worker itself from its slot and the worker count. An explicit worker
    count on the run overrides the density defaults.
    """
    files = _scenario_files(directory, scenario)
    engines = sorted({step.engine for step in scenario.steps}) or ["api"]
    load = scenario.load
    model = load.model
    if run.arrival_rate_per_min:
        model = "open"
    elif run.virtual_users or run.pacing_s is not None:
        model = "closed" if model != "schedule" else model

    total_vus = int(run.virtual_users or load.virtual_users or 1)
    total_rate = float(run.arrival_rate_per_min or load.arrival_rate_per_min or 0.0)
    weights = {engine: 0.0 for engine in engines}
    for persona in scenario.personas:
        persona_engines = {step.engine for step in persona.steps} or {"api"}
        for engine in persona_engines:
            weights[engine] = weights.get(engine, 0.0) + float(persona.weight) / max(1, len(persona_engines))
    weight_total = sum(weights.values()) or 1.0

    groups: List[GroupPlan] = []
    next_slot = 0
    for engine in engines:
        density = settings.browser_contexts_per_worker if engine == "browser" else settings.vus_per_worker
        vus = total_vus if len(engines) == 1 else max(1, round(total_vus * weights[engine] / weight_total))
        rate = total_rate if len(engines) == 1 else total_rate * weights[engine] / weight_total
        if run.workers and run.workers > 0:
            workers = int(run.workers) if len(engines) == 1 else max(1, round(run.workers * weights[engine] / weight_total))
        elif model == "closed":
            workers = max(1, math.ceil(vus / density))
        else:
            workers = 1
        group = GroupPlan(
            engine=engine,
            image=settings.browser_worker_image if engine == "browser" else settings.worker_image,
            workers=workers,
            scenario_files=(
                files if len(engines) == 1
                else {**files, "scenario.yaml": _sub_scenario_yaml(files["scenario.yaml"], engine)}
            ),
        )
        vu_shares = _split_evenly(vus, workers) if model == "closed" else [0] * workers
        for index in range(workers):
            share: Dict[str, Any] = {"model": model, "engine": engine}
            if model == "closed":
                share["virtual_users"] = max(1, vu_shares[index])
            elif model == "open":
                share["arrival_rate_per_min"] = round(rate / workers, 4)
            group.slots.append(SlotPlan(slot=next_slot, engine=engine, share=share))
            next_slot += 1
        groups.append(group)
    return groups


