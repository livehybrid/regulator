"""The fleet: planning a run's workers, leasing them slots, and merging what they report.

A fleet run has the same shape as an in-process one from the outside (a run
row, live statistics, a summary, cache provenance, correlation), and a
different shape inside: the load is generated by N worker containers that
claim slots from this control plane, wait for one shared start instant, run
their share, and post their final report with the raw histograms. This
module owns all of that, adapted from Stoker's lifecycle where the protocol
was proven on real fleets.

The parts, in the order a run meets them:

* :func:`plan` splits the scenario into worker groups (one per engine) and
  each group into per-slot shares of the load.
* :class:`FleetRun` is the per-run supervisor thread: it evicts and reads the
  cache, launches the groups through a driver, watches the leases, releases
  the fleet with T0, handles a stop, notices a worker that stopped heart-
  beating, and finishes the run when every slot is done or lost.
* :func:`claim`, :func:`mark_ready`, :func:`heartbeat` and :func:`final` are
  the request handlers' halves, fenced by lease id so a stale process can
  never speak for a slot somebody else now holds.
* :func:`merge_summaries` turns N worker summaries into one, with the
  percentiles computed once over the merged histograms.
"""

