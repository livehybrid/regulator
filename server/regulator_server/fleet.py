def _leases(session, run: Run) -> List[WorkerLease]:
    return list(
        session.scalars(select(WorkerLease).where(WorkerLease.run_id == run.id).order_by(WorkerLease.slot))
    )


def _find(session, run: Run, slot: int) -> Optional[WorkerLease]:
    return session.scalar(select(WorkerLease).where(WorkerLease.run_id == run.id, WorkerLease.slot == slot))


def _holder_ok(lease: Optional[WorkerLease], lease_id: Optional[str]) -> bool:
    return lease is not None and bool(lease_id) and lease.lease_id == lease_id


def _claim_env(run: Run, target: Target, settings: ServerConfig, share: Dict[str, Any]) -> Dict[str, str]:
    """The standalone environment a worker would have had, from the run row.

    The worker parses this with the same code and validations as a standalone
    run, so there is one way for a value to be wrong.
    """
    cfg = target_config(target)
    env: Dict[str, str] = {
        "REG_TARGET_URL": cfg.url,
        "REG_TARGET_VERIFY_TLS": "1" if cfg.verify_tls else "0",
        "REG_TARGET_APP": cfg.app,
        "REG_TARGET_OWNER": cfg.owner,
        "REG_TARGET_API_VERSION": cfg.api_version,
        "REG_LINT_STRICT": "1",
        # The control plane evicts and reads the cache; workers never touch it.
        "REG_EVICT_CACHE": "0",
    }
    if cfg.web_url:
        env["REG_TARGET_WEB_URL"] = cfg.web_url
    if cfg.token:
        env["REG_TARGET_TOKEN"] = cfg.token
    if cfg.username and cfg.password:
        env["REG_TARGET_USERNAME"] = cfg.username
        env["REG_TARGET_PASSWORD"] = cfg.password
    hec = hec_config(settings)
    if hec is not None:
        env["REG_HEC_URL"] = hec.url
        env["REG_HEC_TOKEN"] = hec.token
        env["REG_HEC_VERIFY_TLS"] = "1" if hec.verify_tls else "0"
        if hec.index:
            env["REG_HEC_INDEX"] = hec.index
    if share.get("model") == "closed" and share.get("virtual_users"):
        env["REG_VUS"] = str(int(share["virtual_users"]))
    if share.get("model") == "open" and share.get("arrival_rate_per_min"):
        env["REG_ARRIVAL_RATE_PER_MIN"] = str(share["arrival_rate_per_min"])
    if run.duration_s:
        env["REG_DURATION_S"] = str(run.duration_s)
    if run.pacing_s is not None:
        env["REG_PACING_S"] = str(run.pacing_s)
    if run.seed:
        env["REG_SEED"] = str(run.seed)
    return env


def claim(session, run: Run, holder: str, hint_slot: Optional[int], files_by_engine: Dict[str, Dict[str, str]]) -> Dict[str, Any]:
    """Issue a lease. Fenced with a fresh lease id every time it changes hands."""
    from fastapi import HTTPException

    if run.fleet_state in (STATE_DRAINING, STATE_FINISHED) or run.state in ("completed", "stopped", "aborted", "failed"):
        raise HTTPException(status_code=409, detail="the run is not accepting claims")
    leases = _leases(session, run)
    # Idempotent for a holder that already has a live lease: a retried claim
    # after a dropped response must not take a second slot.
    for lease in leases:
        if lease.holder == holder and lease.state in LIVE_LEASE_STATES:
            lease.last_heartbeat_at = time.time()
            return _claim_response(session, run, lease, files_by_engine)
    claimable = [lease for lease in leases if lease.state in (LEASE_FREE, LEASE_LOST)]
    if not claimable:
        raise HTTPException(status_code=409, detail="no free lease: every slot is held")
    chosen = None
    if hint_slot is not None:
        chosen = next((lease for lease in claimable if lease.slot == hint_slot), None)
    if chosen is None:
        chosen = claimable[0]
    if chosen.state == LEASE_LOST:
        chosen.restarts = (chosen.restarts or 0) + 1
    chosen.lease_id = secrets.token_urlsafe(16)
    chosen.holder = holder
    chosen.state = LEASE_CLAIMED
    chosen.claimed_at = time.time()
    chosen.last_heartbeat_at = time.time()
    session.add(chosen)
    session.flush()
    return _claim_response(session, run, chosen, files_by_engine)


def _claim_response(session, run: Run, lease: WorkerLease, files_by_engine: Dict[str, Dict[str, str]]) -> Dict[str, Any]:
    settings = get_settings()
    target = session.get(Target, run.target_id)
    share = dict(lease.share_json or {})
    files = files_by_engine.get(lease.engine) or next(iter(files_by_engine.values()), {})
    return {
        "slot": lease.slot,
        "lease_id": lease.lease_id,
        "total_workers": int(run.workers or 1),
        "engine": lease.engine,
        "run_label": f"r{run.id}" + (f"-{run.label}" if run.label else ""),
        "scenario": {"name": run.scenario, "files": files},
        "env": _claim_env(run, target, settings, share),
        "share": share,
        "heartbeat_s": settings.fleet.heartbeat_s,
        "lease_s": settings.fleet.lease_s,
        "t0": run.t0,
    }


def mark_ready(session, run: Run, slot: int, lease_id: Optional[str]) -> None:
    from fastapi import HTTPException

    lease = _find(session, run, slot)
    if not _holder_ok(lease, lease_id):
        raise HTTPException(status_code=409, detail="lease is not the slot holder (superseded)")
    assert lease is not None
    lease.last_heartbeat_at = time.time()
    if lease.state in (LEASE_CLAIMED, LEASE_READY):
        lease.state = LEASE_READY
    session.add(lease)
    session.flush()
    evaluate_release(session, run)


def evaluate_release(session, run: Run, force: bool = False) -> bool:
    """Set T0 once every live lease is ready, or when forced by the timeout."""
    if run.t0 is not None or run.fleet_state not in (STATE_PROVISIONING, None):
        return False
    leases = _leases(session, run)
    ready = [lease for lease in leases if lease.state == LEASE_READY]
    pending = [lease for lease in leases if lease.state in (LEASE_FREE, LEASE_CLAIMED)]
    if not ready:
        return False
    if pending and not force:
        return False
    if pending:
        for lease in pending:
            lease.state = LEASE_LOST
            session.add(lease)
    run.t0 = time.time() + RELEASE_DELAY_S
    run.fleet_state = STATE_RELEASING
    session.add(run)
    log.info("run %s released: T0 in %.0fs, %d worker(s) ready, %d lost", run.id, RELEASE_DELAY_S, len(ready), len(pending))
    return True


def heartbeat(session, run: Run, slot: int, lease_id: Optional[str], payload: Dict[str, Any]) -> Dict[str, Any]:
    """Renew the lease, keep its live statistics, and answer with a command."""
    lease = _find(session, run, slot)
    if not _holder_ok(lease, lease_id):
        return {"command": "superseded"}
    assert lease is not None
    now = time.time()
    lease.last_heartbeat_at = now
    stats = payload.get("stats")
    if isinstance(stats, dict):
        lease.stats_json = stats
    reported = str(payload.get("state") or "")
    if run.fleet_state == STATE_DRAINING or run.state in ("stopped", "aborted", "failed", "completed"):
        session.add(lease)
        return {"command": "stop"}
    if lease.state == LEASE_LOST:
        lease.state = LEASE_RUNNING if run.t0 is not None else LEASE_READY
    if run.t0 is not None and lease.state in (LEASE_CLAIMED, LEASE_READY):
        if reported != "running":
            # Not yet started: tell it T0 again. Repeating the release until
            # the worker says it is running is what makes a heartbeat lost
            # in transit harmless.
            session.add(lease)
            return {"command": "release", "t0": run.t0}
        lease.state = LEASE_RUNNING
        if run.fleet_state == STATE_RELEASING:
            run.fleet_state = STATE_RUNNING
            run.state = "running"
            run.started_at = run.started_at or run.t0
            session.add(run)
    session.add(lease)
    return {"command": "continue"}


def final(session, run: Run, slot: int, lease_id: Optional[str], summary: Dict[str, Any], log_tail: List[str]) -> None:
    """Record a worker's final report. A superseded worker's report is ignored."""
    lease = _find(session, run, slot)
    if lease is None:
        return
    if lease_id and lease.lease_id != lease_id:
        log.info("run %s slot %s: final from a superseded lease ignored", run.id, slot)
        return
    if lease.state != LEASE_DONE:
        lease.summary_json = summary
        lease.log_tail_json = list(log_tail or [])[-200:]
        lease.state = LEASE_DONE
        lease.last_heartbeat_at = time.time()
        session.add(lease)


