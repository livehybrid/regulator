def _hist(documents: Sequence[Optional[Dict[str, Any]]]) -> LatencyHistogram:
    return merge_dicts([doc for doc in documents if isinstance(doc, dict)])


def merge_summaries(run_label: str, scenario: str, summaries: Sequence[Dict[str, Any]], lost_slots: Sequence[int]) -> Dict[str, Any]:
    """One summary from many, with the percentiles computed over the merged histograms.

    Counts add. Histograms add. Peaks add (an upper bound on the fleet's true
    peak, stated as such). Percentiles are never averaged: that was the whole
    reason the workers ship buckets rather than numbers.
    """
    summaries = [s for s in summaries if isinstance(s, dict)]
    stats_list = [s.get("stats") or {} for s in summaries]
    hists = [st.get("histograms") or {} for st in stats_list]

    def total(key: str) -> int:
        return int(sum(int(st.get(key) or 0) for st in stats_list))

    started = min((float(s.get("started_at") or 0) for s in summaries if s.get("started_at")), default=time.time())
    ended = max((float(s.get("ended_at") or 0) for s in summaries if s.get("ended_at")), default=time.time())
    duration = max(0.0, ended - started)
    executions = total("executions")
    errors = total("errors")

    errors_by_class: Dict[str, int] = {}
    for st in stats_list:
        for key, value in (st.get("errors_by_class") or {}).items():
            errors_by_class[key] = errors_by_class.get(key, 0) + int(value or 0)

    latency = _hist([h.get("latency") for h in hists])
    failure = _hist([h.get("failure_latency") for h in hists])
    queued = _hist([h.get("queued") for h in hists])
    loop_lag = _hist([h.get("loop_lag") for h in hists])
    drift = _hist([h.get("drift") for h in hists])

    # Steps, merged by id.
    merged_steps: Dict[str, Dict[str, Any]] = {}
    step_hists: Dict[str, List[Dict[str, Any]]] = {}
    for st, h in zip(stats_list, hists):
        for step in st.get("steps") or []:
            sid = str(step.get("step_id"))
            entry = merged_steps.setdefault(
                sid,
                {"step_id": sid, "class": step.get("class", "unclassified"), "executions": 0, "successes": 0,
                 "partial": 0, "errors": 0, "errors_by_class": {}, "scan_count_total": 0,
                 "result_count_total": 0, "_run_duration_total_s": 0.0},
            )
            for key in ("executions", "successes", "partial", "errors", "scan_count_total", "result_count_total"):
                entry[key] += int(step.get(key) or 0)
            for key, value in (step.get("errors_by_class") or {}).items():
                entry["errors_by_class"][key] = entry["errors_by_class"].get(key, 0) + int(value or 0)
            # The per-search mean carries the duration total back out.
            mean_eps = step.get("mean_events_per_s")
            if mean_eps and step.get("scan_count_total"):
                entry["_run_duration_total_s"] += float(step["scan_count_total"]) / float(mean_eps)
            step_hists.setdefault(sid, []).append((h.get("steps") or {}).get(sid) or {})
    steps_out: List[Dict[str, Any]] = []
    for sid, entry in merged_steps.items():
        parts = step_hists.get(sid, [])
        entry["latency"] = _hist([p.get("latency") for p in parts]).summary()
        entry["failure_latency"] = _hist([p.get("failure_latency") for p in parts]).summary()
        entry["service_time"] = _hist([p.get("service_time") for p in parts]).summary()
        entry["dispatch"] = _hist([p.get("dispatch") for p in parts]).summary()
        entry["ttfr"] = _hist([p.get("ttfr") for p in parts]).summary()
        entry["error_rate_pct"] = round(100.0 * entry["errors"] / entry["executions"], 3) if entry["executions"] else 0.0
        entry["scan_count_per_search"] = (
            round(entry["scan_count_total"] / entry["successes"], 1) if entry["successes"] else None
        )
        duration_total = entry.pop("_run_duration_total_s")
        entry["mean_events_per_s"] = round(entry["scan_count_total"] / duration_total, 1) if duration_total else None
        steps_out.append(entry)

    job_executions = total("job_executions") or sum(
        int((st.get("queueing") or {}).get("job_executions") or 0) for st in stats_list
    )
    searches_queued = sum(int((st.get("queueing") or {}).get("searches_queued") or 0) for st in stats_list)
    peak_in_flight = sum(int(st.get("peak_in_flight") or 0) for st in stats_list)
    max_loop_lag = max((float((st.get("generator") or {}).get("max_loop_lag_ms") or 0) for st in stats_list), default=0.0)
    max_debt = max((float((st.get("generator") or {}).get("max_schedule_debt_ms") or 0) for st in stats_list), default=0.0)

    stats = {
        "run_id": run_label,
        "slot": 0,
        "elapsed_s": round(duration, 2),
        "executions": executions,
        "successes": executions - errors,
        "iterations_completed": total("iterations_completed"),
        "errors": errors,
        "error_rate_pct": round(100.0 * errors / executions, 3) if executions else 0.0,
        "errors_by_class": errors_by_class,
        "partial": total("partial"),
        "abandoned": total("abandoned"),
        "in_flight": 0,
        # A sum of per-worker peaks: an upper bound on the fleet's true peak,
        # since the workers' peaks need not have coincided.
        "peak_in_flight": peak_in_flight,
        "peak_in_flight_note": "sum of the workers' peaks, an upper bound",
        "throughput_per_s": round(executions / duration, 2) if duration > 0 else 0.0,
        "latency": latency.summary(),
        "failure_latency": failure.summary(),
        "queueing": {
            "searches_queued": searches_queued,
            "job_executions": job_executions,
            "queued_pct": round(100.0 * searches_queued / job_executions, 2) if job_executions else 0.0,
            "queued_ms": queued.summary(),
        },
        "generator": {
            "max_loop_lag_ms": round(max_loop_lag, 1),
            "loop_lag_p95_ms": round(loop_lag.percentile_ms(95), 1) if len(loop_lag) else 0.0,
            "max_schedule_debt_ms": round(max_debt, 1),
            "schedule_debt_p95_ms": round(drift.percentile_ms(95), 1) if len(drift) else 0.0,
            "max_drift_ms": round(max_debt, 1),
        },
        "steps": steps_out,
        "arrivals_missed": total("arrivals_missed"),
        "arrivals_shed": total("arrivals_shed"),
        "arrivals_skipped": total("arrivals_skipped"),
        "workers": len(summaries),
    }
    first = summaries[0] if summaries else {}
    target = (first.get("stats") or {}).get("target")
    if target:
        stats["target"] = target

    outcomes = [str(s.get("outcome") or "failed") for s in summaries]
    if "failed" in outcomes:
        outcome = "failed"
    elif "aborted" in outcomes:
        outcome = "aborted"
    elif "stopped" in outcomes:
        outcome = "stopped"
    else:
        outcome = "completed"
    reasons = [str(s.get("invalid_reason")) for s in summaries if s.get("invalid_reason")]
    valid = all(bool(s.get("valid")) for s in summaries) and not lost_slots and bool(summaries)
    if lost_slots:
        reasons.append(
            f"{len(lost_slots)} worker(s) were lost (slots {', '.join(str(s) for s in lost_slots)}): "
            "their share of the load was never applied, so this is not the configured workload"
        )
    if not summaries:
        reasons.append("no worker reported a result")

    configured = dict(first.get("configured_load") or {})
    configured["workers"] = len(summaries) + len(lost_slots)
    per_worker = [s.get("configured_load") or {} for s in summaries]
    if configured.get("model") == "closed":
        configured["virtual_users"] = sum(int(p.get("virtual_users") or 0) for p in per_worker)
    elif configured.get("model") == "open":
        configured["arrival_rate_per_min"] = round(sum(float(p.get("arrival_rate_per_min") or 0) for p in per_worker), 3)
    configured.pop("slot", None)

    return {
        "run_id": run_label,
        "slot": 0,
        "scenario": scenario,
        "outcome": outcome,
        "valid": valid,
        "invalid_reason": "; ".join(reasons) or None,
        "started_at": started,
        "ended_at": ended,
        "duration_s": round(duration, 3),
        "target_url": first.get("target_url"),
        "self_instrumented": any(bool(s.get("self_instrumented")) for s in summaries),
        "co_corrected": all(bool(s.get("co_corrected")) for s in summaries) if summaries else False,
        "load_model": first.get("load_model"),
        "peak_virtual_users": sum(int(s.get("peak_virtual_users") or 0) for s in summaries),
        "stats": stats,
        "cache": None,
        "sut": None,
        "abort_reason": next((s.get("abort_reason") for s in summaries if s.get("abort_reason")), None),
        "scenario_seed": first.get("scenario_seed", 0),
        "effective_seed": first.get("effective_seed", first.get("scenario_seed", 0)),
        "scenario_digest": first.get("scenario_digest"),
        "configured_load": configured,
        "agent_version": first.get("agent_version", ""),
        "workers": [
            {
                "slot": int((s.get("stats") or {}).get("slot") or s.get("slot") or 0),
                "outcome": s.get("outcome"),
                "valid": s.get("valid"),
                "executions": int((s.get("stats") or {}).get("executions") or 0),
                "errors": int((s.get("stats") or {}).get("errors") or 0),
                "p95_ms": ((s.get("stats") or {}).get("latency") or {}).get("p95_ms"),
            }
            for s in summaries
        ] + [{"slot": slot, "outcome": "lost", "valid": False, "executions": 0, "errors": 0, "p95_ms": None} for slot in lost_slots],
    }


def live_snapshot(run: Run, leases: Sequence[WorkerLease]) -> Dict[str, Any]:
    """A fleet's live aggregate from its workers' last heartbeats.

    Counts add; percentiles are those of the largest contributor, labelled as
    such, because a heartbeat carries summaries rather than buckets and the
    honest merge waits for the final reports.
    """
    stats_list = [lease.stats_json for lease in leases if isinstance(lease.stats_json, dict)]
    executions = sum(int(st.get("executions") or 0) for st in stats_list)
    errors = sum(int(st.get("errors") or 0) for st in stats_list)
    biggest = max(stats_list, key=lambda st: int(st.get("executions") or 0), default={})
    elapsed = max((float(st.get("elapsed_s") or 0) for st in stats_list), default=0.0)
    return {
        "run_id": f"r{run.id}",
        "elapsed_s": round(elapsed, 2),
        "executions": executions,
        "errors": errors,
        "error_rate_pct": round(100.0 * errors / executions, 3) if executions else 0.0,
        "in_flight": sum(int(st.get("in_flight") or 0) for st in stats_list),
        "peak_in_flight": sum(int(st.get("peak_in_flight") or 0) for st in stats_list),
        "throughput_per_s": round(sum(float(st.get("throughput_per_s") or 0) for st in stats_list), 2),
        "latency": biggest.get("latency") or LatencyHistogram().summary(),
        "latency_note": "live percentiles are the busiest worker's; the merged figures arrive with the final reports",
        "queueing": {
            "searches_queued": sum(int((st.get("queueing") or {}).get("searches_queued") or 0) for st in stats_list),
            "queued_pct": (biggest.get("queueing") or {}).get("queued_pct", 0.0),
            "queued_ms": (biggest.get("queueing") or {}).get("queued_ms") or LatencyHistogram().summary(),
        },
        "generator": biggest.get("generator") or {},
        "steps": [],
        "workers": [
            {
                "slot": lease.slot,
                "engine": lease.engine,
                "state": lease.state,
                "holder": lease.holder,
                "executions": int((lease.stats_json or {}).get("executions") or 0),
                "errors": int((lease.stats_json or {}).get("errors") or 0),
                "p95_ms": ((lease.stats_json or {}).get("latency") or {}).get("p95_ms"),
                "last_heartbeat_at": lease.last_heartbeat_at,
                "restarts": lease.restarts,
            }
            for lease in leases
        ],
        "fleet_state": run.fleet_state,
        "t0": run.t0,
    }


